#!/usr/bin/env python3
"""Writes the headers of our own arrays in Saturn Maria's build (coop_sat_hud.c's mar_hud.h),
made from the dev machine's Saturn disc by launcher/saturn_maria.py, the converter the
launcher runs. make_patches.py zeroes them again in what ships.

    gen_headers.py <out folder>
"""

import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "launcher"))
import saturn_maria  # noqa: E402

SATURN = HERE.parents[1] / ".env/src/sotn-decomp/disks/saturn"


def main(out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    read = lambda n: (SATURN / n).read_bytes()  # noqa: E731
    vram = struct.unpack(f"<{32 * 96}H", saturn_maria.array_bytes(2, saturn_maria.hud_vram(read("MARIA.PRG"), read("MAR_W.CHR"))))
    rows = ",\n".join("    " + ", ".join(f"0x{v:04X}" for v in vram[k:k + 16]) for k in range(0, len(vram), 16))
    (out / "mar_hud.h").write_text("// Generated by characters/maria-saturn/gen_headers.py from the Saturn disc: never commit\n"
                                   f"u16 mar_hud_vram[{len(vram)}] = {{\n{rows}\n}};\n")


if __name__ == "__main__":
    main(sys.argv[1])
