#!/usr/bin/env python3
"""Finds every stage entity whose code reads g_CastleFlags (design/M2-shared-progression.md,
part 3), so the co-op module can re-initialize it when the partner changes a flag.

    gen_flag_gated.py   -> module/flag_gated.c, docs/flag-gated-entities.md

For each stage under src/st/, the entity table in e_init.c (EntityUpdates[]) gives the update
function behind each entity id (id = index + 1). A function counts as flag-gated if its body,
in the stage's sources or the shared src/st/*.h, mentions g_CastleFlags. Pickups (relic orbs,
item drops) are left out: the module despawns those instead.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ST = ROOT / "src/st"
OUT_C = ROOT / "mods/co-op/module/flag_gated.c"
OUT_MD = ROOT / "mods/co-op/docs/flag-gated-entities.md"
PICKUPS = {"EntityRelicOrb", "EntityPersistentItemDrop", "EntityEquipItemDrop", "EntityPrizeDrop"}
# Scripted sequences: re-initializing one mid-way could replay or cut a scene. Left to room entry.
SCRIPTED = re.compile(r"Cutscene|StageName|Push|Transition|Spawner|Controller|Manager|BossFight")
ANY = 0xFFFF  # the entity indexes g_CastleFlags with an expression: any flag change counts
MAX_FLAGS = 4


def stage_ids():
    """STAGE_xxx enum values from include/game.h."""
    text = (ROOT / "include/game.h").read_text()
    body = text[text.rindex("typedef enum {", 0, text.index("STAGE_NO0 =")):text.index("} Stages;")]
    values, ids = {}, {}
    for m in re.finditer(r"(STAGE_\w+)\s*=\s*([^,\n]+),", body):
        values[m[1]] = m[2].strip()
    def ev(expr):
        expr = expr.split("//")[0].strip()
        for name in sorted(values, key=len, reverse=True):
            expr = expr.replace(name, f"({values[name]})")
        return eval(expr.replace("STAGE_INVERTEDCASTLE_FLAG", "0x20"))  # noqa: S307 (trusted source)
    for name in values:
        try:
            ids[name] = ev(values[name])
        except Exception:
            pass
    return ids


def castle_flag_values():
    text = (ROOT / "include/castle_flags.h").read_text()
    return {m[1]: int(m[2], 0) for m in re.finditer(r"(\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*,", text)}


def flags_read(body, values):
    """Castle flag indices the body reads, or [ANY]."""
    out = set()
    for m in re.finditer(r"g_CastleFlags\s*\[([^\]]+)\]", body):
        expr = m[1].strip()
        if expr in values:
            out.add(values[expr])
        elif re.fullmatch(r"0x[0-9A-Fa-f]+|\d+", expr):
            out.add(int(expr, 0))
        else:
            return [ANY]
    return sorted(out)[:MAX_FLAGS] if len(out) <= MAX_FLAGS else [ANY]


def bodies(files):
    """{function name: body} for every `void Name(Entity* x) {...}` in the files."""
    out = {}
    for f in files:
        text = f.read_text(errors="replace")
        for m in re.finditer(r"\bvoid\s+(\w+)\s*\(\s*Entity\s*\*\s*\w+\s*\)\s*\{", text):
            depth, i = 1, m.end()
            while depth and i < len(text):
                depth += {"{": 1, "}": -1}.get(text[i], 0)
                i += 1
            out.setdefault(m[1], text[m.end():i])
    return out


def main():
    ids = stage_ids()
    values = castle_flag_values()
    shared = bodies(sorted(ST.glob("*.h")))
    rows, report = [], ["# Flag-gated stage entities", "",
                        "Generated by `scripts/gen_flag_gated.py`. When the partner changes one of the castle flags an",
                        "entity reads, the module re-initializes that entity in the current room (unless it's an enemy),",
                        "so walls, doors and switches update live. Scripted sequences (cutscenes, popups, spawners...)",
                        "and anything not listed pick up partner flags on the next room entry.", ""]
    skipped = []
    for init in sorted(ST.glob("*/e_init.c")):
        stage = init.parent.name
        enum = f"STAGE_{stage.upper()}"
        if enum not in ids:
            continue
        text = init.read_text(errors="replace")
        m = re.search(r"EntityUpdates\[\]\s*=\s*\{(.*?)\};", text, re.S)
        if not m:
            continue
        names = [n.strip() for n in re.sub(r"/\*.*?\*/", "", m[1], flags=re.S).split(",") if n.strip()]
        local = bodies(sorted(init.parent.glob("*.c")) + sorted(init.parent.glob("*.h")))
        lines = []
        for index, name in enumerate(names):
            body = local.get(name) or shared.get(name, "")
            if "g_CastleFlags" not in body or name in PICKUPS:
                continue
            if SCRIPTED.search(name):
                skipped.append(f"{stage.upper()} {name}")
                continue
            fl = flags_read(body, values)
            padded = fl + [0] * (MAX_FLAGS - len(fl))
            rows.append(f"    {{{enum}, 0x{index + 1:02X}, {len(fl)}, {{{', '.join(f'0x{f:X}' for f in padded)}}}}}, // {name}")
            lines.append(f"- `0x{index + 1:02X}` {name}: " + ("any flag" if fl == [ANY] else ", ".join(f"`0x{f:X}`" for f in fl)))
        if lines:
            report += [f"## {stage.upper()}", ""] + lines + [""]
    report += ["## Left to room entry (scripted)", ""] + [f"- {s}" for s in skipped] + [""]
    OUT_C.write_text("// Generated by scripts/gen_flag_gated.py: do not edit.\n"
                     "// Stage entities whose code reads g_CastleFlags, and which flags they read.\n"
                     "#define COOP_MODULE\n#include <game.h>\n#include \"flag_gated.h\"\n\n"
                     "const FlagGated g_FlagGated[] = {\n" + "\n".join(rows) + "\n    {-1},\n};\n")
    OUT_MD.write_text("\n".join(report))
    print(f"{len(rows)} entities ({len(skipped)} scripted ones left to room entry) -> {OUT_C.name}, {OUT_MD.name}")


if __name__ == "__main__":
    main()
